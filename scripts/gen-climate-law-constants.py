#!/usr/bin/env python3
"""Generate the climate law's constants from verdify_schemas/climate_law.yaml (plan sections 4.4 and 9).

Outputs, never edited by hand:
  firmware/lib/climate_law_constants_generated.h   namespace climate_law_k, constexpr double / uint32_t
  verdify_schemas/climate_law_constants.py         module-level constants for the host
  docs/climate-law-constants.md                    the documentation table

Each output carries CONSTANTS_SHA256: the SHA-256 of one line per constant, sorted by key, "<key>=<value>\\n", where
<value> is repr() of a float or str() of an int (derived constants included). The firmware publishes it and the host
compares it with the released file.

--check fails when an output differs from regeneration, or when a law source file (LAW_SOURCES) contains a numeric
literal other than 0, 1 or 2: every number in the law comes from the generated header.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "verdify_schemas" / "climate_law.yaml"
OUT_HEADER = REPO_ROOT / "firmware" / "lib" / "climate_law_constants_generated.h"
OUT_PYTHON = REPO_ROOT / "verdify_schemas" / "climate_law_constants.py"
OUT_DOCS = REPO_ROOT / "docs" / "climate-law-constants.md"

# Files that implement the law. A missing file is skipped (the law library lands after the constants file).
LAW_SOURCES = ("firmware/lib/climate_law.h",)
# Numeric literals a law source may contain: none of them is a law number.
ALLOWED_LITERALS = {"0", "1", "2", "0.0", "1.0", "0.0f", "1.0f", "0u", "1u", "0U", "1U", "0UL", "1UL"}

KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")
REQUIRED_FIELDS = ("unit", "group", "what")


def load_constants(path: Path = SOURCE) -> dict[str, dict]:
    """Return {key: {"value": int|float, "unit", "group", "what", "derived": [keys] or None}} in file order."""
    raw = yaml.safe_load(path.read_text())
    entries = raw["constants"]
    out: dict[str, dict] = {}
    for key, spec in entries.items():
        if not KEY_RE.match(key):
            raise ValueError(f"{key}: keys are lower_snake_case")
        for field in REQUIRED_FIELDS:
            if not isinstance(spec.get(field), str) or not spec[field]:
                raise ValueError(f"{key}: missing {field}")
        if ("value" in spec) == ("sum_of" in spec):
            raise ValueError(f"{key}: exactly one of value or sum_of")
        if "value" in spec:
            value = spec["value"]
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise ValueError(f"{key}: value must be a number")
            derived = None
        else:
            derived = list(spec["sum_of"])
            for part in derived:
                if part not in out or out[part]["derived"] is not None:
                    raise ValueError(f"{key}: sum_of names an earlier, non-derived constant ({part})")
            # Rounded so that 0.2 + 0.15 is 0.35, not 0.35000000000000003.
            value = round(sum(float(out[p]["value"]) for p in derived), 9)
        out[key] = {
            "value": value,
            "unit": spec["unit"],
            "group": spec["group"],
            "what": spec["what"],
            "derived": derived,
        }
    return out


def value_text(value: int | float) -> str:
    return str(value) if isinstance(value, int) else repr(float(value))


def constants_sha256(constants: dict[str, dict]) -> str:
    text = "".join(f"{key}={value_text(constants[key]['value'])}\n" for key in sorted(constants))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def cpp_literal(value: int | float) -> str:
    if isinstance(value, int):
        return f"{value}u"
    text = repr(float(value))
    return text if ("." in text or "e" in text) else text + ".0"


def render_header(constants: dict[str, dict]) -> str:
    digest = constants_sha256(constants)
    lines = [
        "// AUTOGENERATED by scripts/gen-climate-law-constants.py from verdify_schemas/climate_law.yaml. DO NOT EDIT.",
        "// Regenerate with: python3 scripts/gen-climate-law-constants.py",
        "// CI (verdify_schemas/tests/test_climate_law_constants.py) fails when this file is stale.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace climate_law_k {",
        "",
        f'constexpr const char* CONSTANTS_SHA256 = "{digest}";',
        "",
    ]
    group = None
    for key, c in constants.items():
        if c["group"] != group:
            group = c["group"]
            lines.append(f"// ---- {group}")
        ctype = "uint32_t" if isinstance(c["value"], int) else "double"
        note = f" (= {' + '.join(c['derived'])})" if c["derived"] else ""
        lines.append(f"// {c['what']} [{c['unit']}]{note}")
        lines.append(f"constexpr {ctype} {key.upper()} = {cpp_literal(c['value'])};")
    lines += ["", "}  // namespace climate_law_k", ""]
    return "\n".join(lines)


def render_python(constants: dict[str, dict]) -> str:
    digest = constants_sha256(constants)
    lines = [
        '"""The climate law constants. AUTOGENERATED from verdify_schemas/climate_law.yaml. DO NOT EDIT.',
        "",
        "Regenerate with: python3 scripts/gen-climate-law-constants.py",
        "CI (verdify_schemas/tests/test_climate_law_constants.py) fails when this file is stale.",
        '"""',
        "",
        f'CONSTANTS_SHA256 = "{digest}"',
        "",
    ]
    group = None
    for key, c in constants.items():
        if c["group"] != group:
            group = c["group"]
            lines.append(f"# ---- {group}")
        note = f" (= {' + '.join(k.upper() for k in c['derived'])})" if c["derived"] else ""
        lines.append(f"# {c['what']} [{c['unit']}]{note}")
        lines.append(f"{key.upper()} = {value_text(c['value'])}")
    lines.append("")
    return "\n".join(lines)


def render_docs(constants: dict[str, dict]) -> str:
    digest = constants_sha256(constants)
    lines = [
        "# Climate law constants",
        "",
        "Generated from `verdify_schemas/climate_law.yaml` by `scripts/gen-climate-law-constants.py`. Do not edit;",
        "change the YAML and regenerate. The firmware compiles these values and reports the hash below; changing one",
        "is a firmware release. Design: `docs/design/climate-refactor-plan-2026-11-15.md`, sections 4.4 and 9.",
        "",
        f"Constants hash (SHA-256): `{digest}`",
        "",
        "| Name | Value | Unit | Group | Meaning |",
        "|---|---:|---|---|---|",
    ]
    for key, c in constants.items():
        what = c["what"] + (f" (sum of {', '.join(f'`{k.upper()}`' for k in c['derived'])})" if c["derived"] else "")
        lines.append(f"| `{key.upper()}` | {value_text(c['value'])} | {c['unit']} | {c['group']} | {what} |")
    lines.append("")
    return "\n".join(lines)


def outputs(constants: dict[str, dict]) -> dict[Path, str]:
    return {
        OUT_HEADER: render_header(constants),
        OUT_PYTHON: render_python(constants),
        OUT_DOCS: render_docs(constants),
    }


_COMMENT_OR_STRING = re.compile(r"//[^\n]*|/\*.*?\*/|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'", re.S)
_NUMBER = re.compile(r"(?<![A-Za-z0-9_.])(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?[fFuUlL]*(?![A-Za-z0-9_.])")


def literal_violations(text: str) -> list[tuple[int, str]]:
    """Numeric literals other than ALLOWED_LITERALS, with their line numbers, outside comments, strings and #lines."""

    def blank(m: re.Match) -> str:
        return re.sub(r"[^\n]", " ", m.group(0))

    code = _COMMENT_OR_STRING.sub(blank, text)
    found = []
    for lineno, line in enumerate(code.splitlines(), start=1):
        if line.lstrip().startswith("#"):
            continue
        for m in _NUMBER.finditer(line):
            if m.group(0) not in ALLOWED_LITERALS:
                found.append((lineno, m.group(0)))
    return found


def check(constants: dict[str, dict]) -> list[str]:
    problems = []
    for path, text in outputs(constants).items():
        rel = path.relative_to(REPO_ROOT)
        if not path.exists() or path.read_text() != text:
            problems.append(f"{rel} is stale: run python3 scripts/gen-climate-law-constants.py")
    for rel in LAW_SOURCES:
        path = REPO_ROOT / rel
        if not path.exists():
            continue
        for lineno, lit in literal_violations(path.read_text()):
            problems.append(f"{rel}:{lineno}: numeric literal {lit}; take it from climate_law_constants_generated.h")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail on a stale output or a typed literal")
    args = parser.parse_args()
    constants = load_constants()
    if args.check:
        problems = check(constants)
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            return 1
        print(f"climate law constants: {len(constants)} constants, outputs current, law sources literal-free")
        return 0
    for path, text in outputs(constants).items():
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
