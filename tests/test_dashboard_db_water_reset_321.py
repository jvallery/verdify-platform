"""Migration 321's water materializer on a private PostgreSQL: a counter reset keeps the gallons used since boot.

The pulse counter restarts from zero at controller boot. Migration 194 booked a reset with no delta, so the gallons
between the boot and the next sample never reached the accepted deltas (iso-2 finding F4). 321 keeps the reset row
and books the counter's value as a delta from zero over the interval since the last sample, under the same quality
rules. This file runs 321's function text unchanged (schema-qualified) over the tables it reads and writes, built
from db/schema.sql's DDL, and compares the accepted total with 194's text over the same samples.

The campaign step starts a fresh server for each tests/test_dashboard_db_*.py file and sets
VERDIFY_ISOLATED_TEST_DSN; without it this file skips.
"""

from __future__ import annotations

import asyncio
import json
import os
from datetime import timedelta
from pathlib import Path

import pytest

asyncpg = pytest.importorskip("asyncpg")

pytestmark = pytest.mark.skipif(
    not os.environ.get("VERDIFY_ISOLATED_TEST_DSN"),
    reason="needs the campaign step's private PostgreSQL (VERDIFY_ISOLATED_TEST_DSN)",
)

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = "water_reset_321"
M194 = (ROOT / "db/migrations/194-scope-aware-resource-accounting.sql").read_text()
M321 = (ROOT / "db/migrations/321-ingestor-gap-and-compliance-reads-water-reset-delta.sql").read_text()
FUNCTION_START = "CREATE OR REPLACE FUNCTION public.materialize_water_meter_events("
TABLES = ("climate", "equipment_state", "system_state", "water_meter_events", "water_meter_materializer_state")


def extract(text: str, start: str, end: str) -> str:
    assert text.count(start) == 1, start
    begin = text.index(start)
    return text[begin : text.index(end, begin) + len(end)].replace("public.", f"{SCHEMA}.")


def function(text: str) -> str:
    return extract(text, FUNCTION_START, "\n$$;")


def ddl() -> list[str]:
    schema = (ROOT / "db/schema.sql").read_text()
    return [
        f"CREATE TABLE {SCHEMA}.climate (ts timestamptz NOT NULL, greenhouse_id text, water_total_gal double precision)",
        f"CREATE TABLE {SCHEMA}.equipment_state (ts timestamptz NOT NULL, greenhouse_id text, equipment text, "
        "state boolean)",
        f"CREATE TABLE {SCHEMA}.system_state (ts timestamptz NOT NULL, greenhouse_id text, entity text, value text)",
        extract(schema, "CREATE TABLE public.water_meter_events (", ");\n"),
        f"ALTER TABLE {SCHEMA}.water_meter_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY",
        f"ALTER TABLE {SCHEMA}.water_meter_events ADD UNIQUE (ts, source, meter_id, event_type)",
        extract(schema, "CREATE TABLE public.water_meter_materializer_state (", ");\n"),
        f"ALTER TABLE {SCHEMA}.water_meter_materializer_state ADD PRIMARY KEY (greenhouse_id, source, meter_id)",
    ]


@pytest.fixture(scope="module")
def dsn():
    from conftest import isolated_mutation_test_dsn

    value = isolated_mutation_test_dsn()

    async def run(statements):
        conn = await asyncpg.connect(value)
        try:
            for s in statements:
                await conn.execute(s)
        finally:
            await conn.close()

    asyncio.run(run([f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE", f"CREATE SCHEMA {SCHEMA}", *ddl()]))
    yield value
    asyncio.run(run([f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE"]))


def materialize(dsn, text: str, samples: list[tuple[int, float]], relays: list[tuple[int, str, bool]] = ()):
    """Load samples (seconds after t0, counter gallons) and relay edges (seconds, relay, state), run the given
    migration's function, return its events."""

    async def run():
        conn = await asyncpg.connect(dsn)
        try:
            await conn.execute(f"SET search_path = {SCHEMA}")
            await conn.execute(f"TRUNCATE {', '.join(TABLES)}")
            await conn.execute(function(text))
            t0 = await conn.fetchval("SELECT date_trunc('minute', now()) - interval '2 hours'")
            await conn.executemany(
                "INSERT INTO climate (ts, greenhouse_id, water_total_gal) VALUES ($1, 'vallery', $2)",
                [(t0 + timedelta(seconds=s), gal) for s, gal in samples],
            )
            await conn.executemany(
                "INSERT INTO equipment_state (ts, greenhouse_id, equipment, state) VALUES ($1, 'vallery', $2, $3)",
                [(t0 + timedelta(seconds=s), relay, state) for s, relay, state in relays],
            )
            await conn.fetchrow(f"SELECT * FROM {SCHEMA}.materialize_water_meter_events('vallery', now())")
            rows = await conn.fetch(
                "SELECT ts, event_type, delta_gal, quality_flag, prior_ts, prior_total_gal, raw, materializer_revision, "
                "attribution_class, attributed_scope "
                "FROM water_meter_events ORDER BY ts, event_type"
            )
            return t0, rows
        finally:
            await conn.close()

    return asyncio.run(run())


def accepted(rows) -> float:
    """What the daily water total counts (migration 304): delta events of quality ok."""
    return round(sum(r["delta_gal"] for r in rows if r["event_type"] == "delta" and r["quality_flag"] == "ok"), 3)


# 500 then 501 gal; the controller reboots, reads 0, then 0.6 and 1.0 gal since boot. All samples 60 s apart.
BOOT = [(0, 500.0), (60, 501.0), (120, 0.0), (180, 0.6), (240, 1.0)]


def test_a_short_reboot_keeps_the_gallons_used_since_boot(dsn):
    t0, rows = materialize(dsn, M321, BOOT)
    kinds = [(r["event_type"], r["quality_flag"]) for r in rows]
    assert kinds == [
        ("initial", "ok"),
        ("delta", "ok"),
        ("phantom_zero", "phantom_zero"),
        ("delta", "ok"),
        ("reset", "counter_reset"),
        ("delta", "ok"),
    ]
    after_reset = rows[3]
    assert after_reset["ts"] == t0 + timedelta(seconds=180)
    # The interval starts at the counter's zero reading after the boot, not at the last sample before it.
    assert (after_reset["prior_ts"], after_reset["prior_total_gal"]) == (t0 + timedelta(seconds=120), 0.0)
    assert after_reset["delta_gal"] == pytest.approx(0.6)
    assert '"after_counter_reset": true' in after_reset["raw"]
    assert rows[4]["delta_gal"] == 0  # the reset row itself still carries no volume
    assert {r["materializer_revision"] for r in rows} == {"migration_321"}
    assert accepted(rows) == 2.0  # 1 before the reboot, 0.6 + 0.4 after it


def test_194_lost_the_gallons_before_the_first_sample_after_boot(dsn):
    _, rows = materialize(dsn, M194, BOOT)
    assert accepted(rows) == 1.4  # the 0.6 gal used since boot were dropped


def test_a_reboot_after_a_silence_counts_from_the_zero_readings(dsn):
    # 11-17 17:16Z (iso-2): silent 30 minutes, then the rebooted counter reads 0 for 25 minutes and 1 gal a minute
    # later. 194 dropped that gallon; 321 books it as an ok delta from the newest zero reading.
    zeros = [(1860 + 60 * i, 0.0) for i in range(25)]
    t0, rows = materialize(dsn, M321, [(0, 4.0), (60, 4.0), *zeros, (3360, 1.0), (3420, 2.0)])
    deltas = [(r["prior_ts"], r["delta_gal"], r["quality_flag"]) for r in rows if r["event_type"] == "delta"]
    assert deltas == [(t0 + timedelta(seconds=3300), 1.0, "ok"), (t0 + timedelta(seconds=3360), 1.0, "ok")]
    assert accepted(rows) == 2.0
    _, old = materialize(dsn, M194, [(0, 4.0), (60, 4.0), *zeros, (3360, 1.0), (3420, 2.0)])
    assert accepted(old) == 1.0


def test_a_long_outage_keeps_the_volume_out_of_ok_delivery(dsn):
    # The counter was silent for 30 minutes across the reboot and never read zero: the delta is source_gap, as any
    # delta after a gap.
    _, rows = materialize(dsn, M321, [(0, 500.0), (60, 501.0), (1860, 3.0), (1920, 3.5)])
    deltas = [(r["delta_gal"], r["quality_flag"]) for r in rows if r["event_type"] == "delta"]
    assert deltas == [(1.0, "ok"), (pytest.approx(3.0), "source_gap"), (pytest.approx(0.5), "ok")]
    assert accepted(rows) == 1.5


def test_a_drop_that_is_not_a_reboot_is_held_out_as_a_high_delta(dsn):
    # A glitch reading of 470 after 501 is booked as a reset; its 470 gal exceed 25 and stay out of ok delivery.
    # #1668 item 2: the high_delta row stores 0 and keeps the 470 gal in raw, so an unfiltered sum is safe.
    _, rows = materialize(dsn, M321, [(0, 500.0), (60, 501.0), (120, 470.0), (180, 470.5)])
    deltas = [(r["delta_gal"], r["quality_flag"]) for r in rows if r["event_type"] == "delta"]
    assert deltas == [(1.0, "ok"), (0.0, "high_delta"), (0.5, "ok")]
    assert json.loads(rows[[r["quality_flag"] for r in rows].index("high_delta")]["raw"])["held_delta_gal"] == 470.0
    assert accepted(rows) == 1.5
    assert round(sum(r["delta_gal"] for r in rows), 3) == 1.5


def test_an_overlap_of_wetting_relays_only_is_climate_wetting(dsn):
    # #1668 item 3: fog and a mister both start inside one meter interval; the class stays ambiguous_overlap and the
    # scope is climate_wetting. A drip in the overlap keeps the scope empty.
    wet = [(70, "fog", True), (80, "mister_south", True), (110, "fog", False), (115, "mister_south", False)]
    _, rows = materialize(dsn, M321, [(0, 10.0), (60, 10.0), (120, 12.0)], wet)
    delta = [r for r in rows if r["event_type"] == "delta"][-1]
    assert (delta["attribution_class"], delta["attributed_scope"]) == ("ambiguous_overlap", "climate_wetting")
    mixed = [(70, "fog", True), (80, "drip_wall", True), (110, "fog", False), (115, "drip_wall", False)]
    _, rows = materialize(dsn, M321, [(0, 10.0), (60, 10.0), (120, 12.0)], mixed)
    delta = [r for r in rows if r["event_type"] == "delta"][-1]
    assert (delta["attribution_class"], delta["attributed_scope"]) == ("ambiguous_overlap", None)


def test_the_one_time_rewrites_zero_flaps_and_scope_wetting_overlaps(dsn):
    # Rows booked by 194 (a 499 gal flap; a fog + mister overlap with no scope), then 321's two UPDATE statements.
    zero = extract(M321, "UPDATE public.water_meter_events\n   SET raw = COALESCE", "? 'held_delta_gal');")
    scope = extract(M321, "UPDATE public.water_meter_events\n   SET attributed_scope", "]::text[];")
    wet = [(70, "fog", True), (80, "mister_south", True), (110, "fog", False), (115, "mister_south", False)]

    async def run():
        conn = await asyncpg.connect(dsn)
        try:
            await conn.execute(f"SET search_path = {SCHEMA}")
            for _ in range(2):  # idempotent
                await conn.execute(zero)
                await conn.execute(scope)
            return await conn.fetch(
                "SELECT delta_gal, quality_flag, raw, attributed_scope FROM water_meter_events "
                "WHERE event_type = 'delta' ORDER BY ts"
            )
        finally:
            await conn.close()

    materialize(dsn, M194, [(0, 500.0), (60, 501.0), (120, 1000.0)])  # 194 stores the 499 gal flap as its delta
    rows = asyncio.run(run())
    flap = [r for r in rows if r["quality_flag"] == "high_delta"][0]
    assert flap["delta_gal"] == 0 and json.loads(flap["raw"])["held_delta_gal"] == 499.0
    materialize(dsn, M194, [(0, 10.0), (60, 10.0), (120, 12.0)], wet)
    rows = asyncio.run(run())
    assert rows[-1]["attributed_scope"] == "climate_wetting"


def test_the_one_time_backfill_adds_the_gallons_194_dropped(dsn):
    # Booked by 194 (reset with no delta), then 321's backfill statement: the dropped gallon becomes an ok delta from
    # the newest zero reading, once.
    samples = [(0, 4.0), (60, 4.0), *[(1860 + 60 * i, 0.0) for i in range(25)], (3360, 1.0), (3420, 2.0)]
    backfill = extract(
        M321,
        "INSERT INTO public.water_meter_events (\n    ts, greenhouse_id, source, meter_id, event_type, prior_ts, prior_total_gal",
        "AND d.event_type = 'delta');",
    )

    t0, old = materialize(dsn, M194, samples)
    assert accepted(old) == 1.0

    async def apply():
        conn = await asyncpg.connect(dsn)
        try:
            await conn.execute(f"SET search_path = {SCHEMA}")
            first = await conn.execute(backfill)
            second = await conn.execute(backfill)
            rows = await conn.fetch(
                "SELECT ts, event_type, delta_gal, quality_flag, prior_ts, prior_total_gal, raw, materializer_revision, "
                "attribution_quality FROM water_meter_events ORDER BY ts, event_type"
            )
            return first, second, rows
        finally:
            await conn.close()

    first, second, rows = asyncio.run(apply())
    assert (first, second) == ("INSERT 0 1", "INSERT 0 0")
    added = [r for r in rows if r["attribution_quality"] == "reset_backfill_321"]
    assert len(added) == 1
    assert (added[0]["prior_ts"], added[0]["delta_gal"], added[0]["quality_flag"]) == (
        t0 + timedelta(seconds=3300),
        1.0,
        "ok",
    )
    assert accepted(rows) == 2.0
